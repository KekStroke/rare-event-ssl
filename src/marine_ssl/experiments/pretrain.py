AMP_RETRY_POLICY = "amp-fp16-same-batch-retry-v1"
AMP_COMPATIBLE_PRETRAIN_SHA256 = "74dd527d426f4d65f34179b38ce364e15df7839940733bd45152411257af9ffc"


def implementation_sources():
    root = Path(__file__).parent
    return {name: digest(root / name) for name in ("pretrain.py", "codebook.py", "encoders.py", "ssl_data.py")}


def validate_resume_implementation(config, receipt_path, *, resume, config_path):
    """Authorize one explicit implementation-only migration, preserving recipe bytes."""
    if resume is None or config_path is None:
        raise ValueError("implementation receipt requires explicit resume and original config path")
    receipt = json.loads(Path(receipt_path).read_text())
    original, actual = config.get("training_source_sha256"), implementation_sources()
    if (receipt.get("schema_version") != 1 or receipt.get("policy_id") != AMP_RETRY_POLICY
            or not isinstance(original, dict) or set(original) != set(actual)
            or original.get("pretrain.py") != AMP_COMPATIBLE_PRETRAIN_SHA256
            or receipt.get("original_training_source_sha256") != original
            or receipt.get("actual_training_source_sha256") != actual
            or any(actual[name] != original[name] for name in actual if name != "pretrain.py")
            or receipt.get("config_sha256") != digest(config_path)
            or receipt.get("recipe_fingerprint") != fingerprint(config)):
        raise ValueError("unverified resume implementation/config/source migration")
    latest = json.loads((Path(config["output_dir"]) / "latest.json").read_text())
    if receipt.get("run_signature") != latest.get("signature"):
        raise ValueError("implementation receipt identifies a different existing run")
    return {**receipt, "receipt_sha256": digest(receipt_path)}


def device_telemetry(device):
    """Process-local memory peaks; CPU reporting does not initialize CUDA."""
    import torch
    resolved = torch.device(device)
    result = {"device": str(resolved), "device_type": resolved.type, "device_name": "CPU",
              "device_total_memory_bytes": None, "gpu_allocated_bytes": None,
              "gpu_reserved_bytes": None, "gpu_peak_allocated_bytes": None,
              "gpu_peak_reserved_bytes": None}
    if resolved.type == "cuda":
        index = resolved.index if resolved.index is not None else torch.cuda.current_device()
        properties = torch.cuda.get_device_properties(index)
        result.update(device_name=properties.name, device_total_memory_bytes=int(properties.total_memory),
                      cuda_capability=[int(properties.major), int(properties.minor)],
                      gpu_allocated_bytes=int(torch.cuda.memory_allocated(index)),
                      gpu_reserved_bytes=int(torch.cuda.memory_reserved(index)),
                      gpu_peak_allocated_bytes=int(torch.cuda.max_memory_allocated(index)),
                      gpu_peak_reserved_bytes=int(torch.cuda.max_memory_reserved(index)))
    return result


def learning_rate(update, total_updates, *, peak=5e-5, warmup_updates=5000):
    """Fairseq polynomial decay, power one, end LR zero; first update is one."""
    if total_updates < 1 or update < 0 or warmup_updates < 0:
        raise ValueError("invalid LR schedule")
    if warmup_updates and update <= warmup_updates:
        return peak * update / warmup_updates
    if update >= total_updates:
        return 0.0
    return peak * max(0.0, (total_updates - update) / max(1, total_updates - warmup_updates))


def build_model(*, tiny=False):
    """Public TorchAudio factory, all relevant historical parameters explicit."""
    import torchaudio
    model = torchaudio.models.hubert_pretrain_model(
        extractor_mode="group_norm",
        extractor_conv_layer_config=[(8 if tiny else 512, k, s) for k, s in [(10, 5), (3, 2), (3, 2), (3, 2), (3, 2), (2, 2), (2, 2)]],
        extractor_conv_bias=False, encoder_embed_dim=16 if tiny else 768,
        encoder_projection_dropout=.1, encoder_pos_conv_kernel=16 if tiny else 128,
        encoder_pos_conv_groups=2 if tiny else 16, encoder_num_layers=2 if tiny else 12,
        encoder_num_heads=2 if tiny else 12, encoder_attention_dropout=.1,
        encoder_ff_interm_features=32 if tiny else 3072, encoder_ff_interm_dropout=0.0,
        encoder_dropout=.1, encoder_layer_norm_first=False, encoder_layer_drop=.05,
        mask_prob=.8, mask_selection="static", mask_other=0.0, mask_length=10,
        no_mask_overlap=False, mask_min_space=1, mask_channel_prob=0.0,
        mask_channel_selection="static", mask_channel_other=0.0, mask_channel_length=10,
        no_mask_channel_overlap=False, mask_channel_min_space=1, skip_masked=False,
        skip_nomask=True, num_classes=200, final_dim=8 if tiny else 256, feature_grad_mult=.1)
    return model


def objective_sum(logits_masked, feature_penalty):
    """Sum of masked-frame CE + 10*feature_penalty per masked frame."""
    import torch
    from torch.nn import functional as functional
    if logits_masked is None or logits_masked.ndim != 2 or logits_masked.shape[0] == 0:
        raise ValueError("HuBERT produced no masked frames")
    count = logits_masked.shape[0]
    target = torch.zeros(count, dtype=torch.long, device=logits_masked.device)
    cross_entropy = functional.cross_entropy(logits_masked.float(), target, reduction="sum")
    return cross_entropy + feature_penalty.float() * (10.0 * count), count


def make_optimizer(parameters):
    """Fairseq 'adam' uses decoupled decay; torch AdamW preserves that policy.

    Fairseq's custom/fused implementations can place epsilon differently in
    bias correction. This is a documented recipe repeat, not bitwise replay of
    an unknown historical optimizer kernel/state.
    """
    import torch
    return torch.optim.AdamW(parameters, lr=5e-5, betas=(.9, .98), eps=1e-6, weight_decay=.01)


def initialize_student(spec, device):
    """Use the registered strict adapter and official HF importer; no key guesses."""
    from .encoders import load_encoder
    from torchaudio.models.wav2vec2.utils import import_huggingface_model
    adapter = load_encoder(spec, "cpu")
    backbone = adapter.model if adapter.kind == "aves_torchaudio" else import_huggingface_model(adapter.model)
    student = build_model()
    student.wav2vec2.load_state_dict(backbone.state_dict(), strict=True)
    student.input_normalize_waveform = bool(adapter.normalize_waveform)
    student.requires_grad_(True).to(device)
    return student


def prepare_waveforms(waveforms, model):
    """Per-clip preprocessing verified by the registered published adapter."""
    if getattr(model, "input_normalize_waveform", False):
        return (waveforms - waveforms.mean(-1, keepdim=True)) / (waveforms.var(-1, unbiased=False, keepdim=True) + 1e-7).sqrt()
    return waveforms


def capture_rng():
    import numpy as np
    import torch
    return {"python": random.getstate(), "numpy": np.random.get_state(), "torch": torch.get_rng_state(),
            "cuda": torch.cuda.get_rng_state_all() if torch.cuda.is_available() else []}


def restore_rng(state):
    import numpy as np
    import torch
    random.setstate(state["python"]); np.random.set_state(state["numpy"])
    torch.set_rng_state(state["torch"].cpu())
    if state["cuda"]:
        torch.cuda.set_rng_state_all(state["cuda"])


def seed_everything(seed):
    import numpy as np
    import torch
    random.seed(seed); np.random.seed(seed); torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


class LabeledTarDataset(TarAudioDataset):
    """At most one recording's uint8 labels resident; no WAV/feature cache."""
    def __init__(self, index, database, *, consumed=None, **kwargs):
        super().__init__(index, **kwargs)
        self.database = str(database)
        self.consumed = dict(consumed or {})

    def __iter__(self):
        import numpy as np
        import torch
        from torch.utils.data import get_worker_info
        if get_worker_info() is not None:
            raise RuntimeError("training cursor version one requires DataLoader num_workers=0")
        connection = sqlite3.connect(Path(self.database).absolute().as_uri() + "?mode=ro&immutable=1", uri=True)
        epoch_seed = int.from_bytes(hashlib.sha256(_json_bytes([self.seed, self.epoch])).digest()[:8], "big")
        rows = _shuffle((row for _, row in _rows(self.index)), random.Random(epoch_seed), self.shard_shuffle_buffer)
        try:
            for row in rows:
                skipped = self.consumed.get(row["tar_path"], 0)
                if not 0 <= skipped <= row["segment_count"]:
                    raise ValueError("resume member cursor exceeds recording length")
                if skipped == row["segment_count"]:
                    continue
                target = connection.execute("SELECT members,labels,checksum FROM recordings WHERE tar_path=?", (row["tar_path"],)).fetchone()
                if target is None or hashlib.sha256(target[1]).hexdigest() != target[2]:
                    raise ValueError("missing/corrupt recording targets: " + row["tar_path"])
                members = json.loads(target[0])
                labels = np.frombuffer(target[1], dtype="uint8").reshape(-1, 249)
                if len(members) != row["segment_count"] or len(labels) != len(members):
                    raise ValueError("label member count mismatch")
                for i, sample in enumerate(iter_tar_samples([row], shard_shuffle_buffer=0)):
                    if sample["member"] != members[i]:
                        raise ValueError("label member order differs from audio TAR")
                    if i < skipped:
                        continue
                    yield {"waveform": torch.tensor(sample["waveform"], dtype=torch.float32) / 32768.0,
                           "labels": torch.tensor(labels[i].astype("int64")), "sample_id": sample["sample_id"],
                           "tar_path": row["tar_path"], "member_index": i}
        finally:
            connection.close()


def collate_samples(samples):
    import torch
    return {"waveform": torch.stack([sample["waveform"] for sample in samples]),
            "labels": torch.stack([sample["labels"] for sample in samples]),
            "cursor": [(sample["tar_path"], sample["member_index"]) for sample in samples]}


def _autocast(device, precision):
    import torch
    if precision == "fp32":
        return nullcontext()
    if not str(device).startswith("cuda"):
        raise ValueError("fp16/bf16 training requires a CUDA device")
    return torch.autocast("cuda", dtype=torch.float16 if precision == "fp16" else torch.bfloat16)


def backward_group(model, optimizer, scaler, batches, *, device, precision, max_retries=8):
    """Retry AMP overflow on the retained group; commit no optimizer/data step here.

    The RNG snapshot is taken after data fetch. Standard GradScaler skip/update
    performs backoff and resets its growth tracker; finite-gradient norm overflow
    and nonfinite objectives remain fatal rather than being silently clipped.
    """
    import torch
    if max_retries < 0:
        raise ValueError("negative AMP retry budget")
    prior = capture_rng()
    denominator = 140 * 249
    for retry in range(max_retries + 1):
        if retry:
            restore_rng(prior)
        optimizer.zero_grad(set_to_none=True)
        masked_count, loss_sum = 0, 0.0
        for batch in batches:
            with _autocast(device, precision):
                masked, _, penalty = model(prepare_waveforms(batch["waveform"].to(device, non_blocking=True), model),
                                            batch["labels"].to(device, non_blocking=True))
                loss, count = objective_sum(masked, penalty)
            if not bool(torch.isfinite(loss)):
                raise FloatingPointError("nonfinite HuBERT objective; prior checkpoint is preserved")
            scaler.scale(loss / denominator).backward()
            masked_count += count; loss_sum += float(loss.detach())
        scaler.unscale_(optimizer)
        parameters = [parameter for parameter in model.parameters() if parameter.grad is not None]
        finite = bool(torch.stack([torch.isfinite(parameter.grad).all() for parameter in parameters]).all())
        if not finite:
            if precision != "fp16" or not scaler.is_enabled():
                raise FloatingPointError("nonfinite unscaled gradients without FP16 GradScaler")
            before = float(scaler.get_scale())
            # unscale_ already recorded found_inf. This MUST skip AdamW and use
            # the official scaler backoff/growth-tracker reset, not manual scale.
            scaler.step(optimizer); scaler.update()
            after = float(scaler.get_scale())
            print(json.dumps({"stage": "amp_overflow_retry", "policy": AMP_RETRY_POLICY,
                              "retry": retry + 1, "scale_before": before, "scale_after": after}), flush=True)
            if not math.isfinite(after) or not 0 < after < before or retry == max_retries:
                raise FloatingPointError("FP16 gradient overflow exhausted bounded same-batch retry")
            continue
        for parameter in parameters:
            parameter.grad.mul_(denominator / masked_count)
        norm = torch.nn.utils.clip_grad_norm_(model.parameters(), 10.0, error_if_nonfinite=True)
        return masked_count, loss_sum, norm, retry


def _loader(config, split, epoch, consumed=None):
    import torch
    dataset = LabeledTarDataset(config[f"{split}_index"], Path(config["labels_dir"]) / "labels.sqlite",
                                consumed=consumed, epoch=epoch, seed=int(config.get("seed", 20261103)),
                                shard_shuffle_buffer=int(config.get("shard_shuffle_buffer", 100000)) if split == "train" else 0)
    return torch.utils.data.DataLoader(dataset, batch_size=int(config.get("microbatch_size", 70)),
                                       num_workers=0, collate_fn=collate_samples,
                                       generator=torch.Generator().manual_seed(int(config.get("seed", 20261103)) + epoch),
                                       pin_memory=str(config.get("device", "cuda")).startswith("cuda"))


def validate(model, loader, *, device, precision, seed):
    import torch
    prior, training = capture_rng(), model.training
    seed_everything(seed)
    model.eval()
    total_loss, total_masked, samples, last_log = 0.0, 0, 0, time.monotonic()
    try:
        with torch.inference_mode():
            for batch in loader:
                with _autocast(device, precision):
                    masked, _, penalty = model(prepare_waveforms(batch["waveform"].to(device), model), batch["labels"].to(device))
                    loss, count = objective_sum(masked, penalty)
                total_loss += float(loss); total_masked += count; samples += len(batch["cursor"])
                if time.monotonic() - last_log >= 60:
                    print(json.dumps({"stage": "validation", "samples": samples}), flush=True)
                    last_log = time.monotonic()
        if not total_masked or not math.isfinite(total_loss):
            raise ValueError("SSL validation is empty or nonfinite")
        return {"masked_objective": total_loss / total_masked, "masked_frames": total_masked, "samples": samples,
                "selection": "minimum fixed-mask held-out SSL objective; no downstream test selection"}
    finally:
        model.train(training); restore_rng(prior)


def _atomic_torch_save(path, value):
    import torch
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".part")
    torch.save(value, temporary)
    temporary.replace(path)


def _save_checkpoint(output, state, history, *, is_best, keep_last):
    """Prune only checkpoint paths recorded as owned by this run."""
    name = f"checkpoint_{state['global_step']:09d}.pt"
    path = output / "checkpoints" / name
    best = name if is_best else state.get("best_checkpoint")
    state = {**state, "best_checkpoint": best}
    _atomic_torch_save(path, state)
    record = {"name": name, "step": state["global_step"], "sha256": digest(path)}
    history = [item for item in history if item["name"] != name] + [record]
    retained = {item["name"] for item in sorted(history, key=lambda row: row["step"])[-keep_last:]}
    if best:
        retained.add(best)
    write_json(output / "latest.json", {**record, "signature": state["signature"], "best_checkpoint": best,
                                         "history": [item for item in history if item["name"] in retained]})
    root = (output / "checkpoints").resolve()
    for old in history:
        if old["name"] not in retained:
            candidate = root / old["name"]
            if candidate.parent != root or not re.fullmatch(r"checkpoint_\d{9}\.pt", old["name"]):
                raise ValueError("unsafe checkpoint retention path")
            if candidate.exists():
                candidate.unlink()
    return [item for item in history if item["name"] in retained], best


def train(config, *, resume=None, stop_after_updates=None, resume_implementation_receipt=None, config_path=None):
    import numpy as np
    import torch
    import torchaudio
    implementation = None
    if resume_implementation_receipt is not None:
        implementation = validate_resume_implementation(config, resume_implementation_receipt,
                                                        resume=resume, config_path=config_path)
    elif config.get("training_source_sha256") and config["training_source_sha256"] != implementation_sources():
        raise ValueError("training implementation differs; explicit verified resume implementation receipt required")
    if int(config.get("workers", 0)) != 0:
        raise ValueError("exact committed-member resume currently requires workers=0")
    device, precision = config.get("device", "cuda"), config.get("precision", "fp16")
    if precision not in {"fp16", "bf16", "fp32"}:
        raise ValueError("unknown precision")
    microbatch, accumulation = int(config.get("microbatch_size", 70)), int(config.get("accumulation_steps", 2))
    if microbatch < 1 or accumulation < 1 or microbatch * accumulation != 140:
        raise ValueError("historical effective batch must be exactly 140 clips")
    train_info, val_info = index_info(config, "train"), index_info(config, "validation")
    if not train_info["samples"] or not val_info["samples"]:
        raise ValueError("nonempty group-disjoint SSL train and validation splits required")
    labels = json.loads((Path(config["labels_dir"]) / "labels.ready.json").read_text())
    if any(labels["indexes"][split]["sha256"] != info["sha256"] for split, info in (("train", train_info), ("validation", val_info))):
        raise ValueError("target database was generated for different data splits")
    if digest(Path(config["labels_dir"]) / "labels.sqlite") != labels["database_sha256"]:
        raise ValueError("target database checksum mismatch")
    epochs, seed = int(config.get("epochs", 10)), int(config.get("seed", 20261103))
    if (epochs < 1 or int(config.get("keep_last", 2)) < 1
            or int(config.get("checkpoint_interval_updates", 1000)) < 1
            or int(config.get("validation_interval_updates", 1000)) < 1
            or (stop_after_updates is not None and stop_after_updates < 1)):
        raise ValueError("positive epoch/retention/interval/pilot counts required")
    total_updates = math.ceil(train_info["samples"] / 140) * epochs
    signature = fingerprint({"config": {k: v for k, v in config.items() if k not in {"device", "output_dir"}},
                             "train": train_info, "validation": val_info, "labels": labels["signature"],
                             "optimizer": "torch.optim.AdamW-decoupled-v1",
                             "objective": "torchaudio-hubert-cosine-nce-k200-d256-temp0.1-masked1-feature10-v1"})
    if implementation is not None and implementation["run_signature"] != signature:
        raise ValueError("implementation receipt does not preserve recipe/data/schedule signature")
    output = Path(config["output_dir"]); output.mkdir(parents=True, exist_ok=True)
    if (output / "latest.json").exists() and resume is None:
        raise ValueError("existing run requires explicit --resume auto or checkpoint path")
    seed_everything(seed)
    model = initialize_student(config["initial_encoder"], device)
    optimizer = make_optimizer(model.parameters())
    scaler = torch.cuda.amp.GradScaler(enabled=precision == "fp16")
    state = {"signature": signature, "global_step": 0, "epoch": 0, "consumed": {},
             "best_validation": None, "best_checkpoint": None, "total_updates": total_updates}
    history = []
    if resume is not None:
        latest = json.loads((output / "latest.json").read_text())
        path = output / "checkpoints" / latest["name"] if resume == "auto" else Path(resume)
        record = next((row for row in latest["history"] if row["name"] == path.name), None)
        if not record or digest(path) != record["sha256"]:
            raise ValueError("resume checkpoint is not an owned, checksum-verified retained checkpoint")
        loaded = torch.load(path, map_location="cpu", weights_only=False)
        if loaded["signature"] != signature or loaded["total_updates"] != total_updates:
            raise ValueError("resume configuration/data/schedule is incompatible")
        model.load_state_dict(loaded.pop("model"), strict=True)
        optimizer.load_state_dict(loaded.pop("optimizer")); scaler.load_state_dict(loaded.pop("scaler"))
        restore_rng(loaded.pop("rng")); state = loaded; history = latest["history"]
    import torchaudio.models.wav2vec2.components as components
    versions = {"torch": torch.__version__, "torchaudio": torchaudio.__version__, "numpy": np.__version__}
    provenance = {"config": config, "signature": signature, "train": train_info, "validation": val_info,
                  "labels": labels, "versions": versions, "total_updates": total_updates,
                  "official_nce_source_sha256": hashlib.sha256(inspect.getsource(components._compute_logits).encode()).hexdigest(),
                  "objective_reference": "https://github.com/pytorch/audio/blob/v2.2.2/src/torchaudio/models/wav2vec2/components.py",
                  "effective_batch_clips": 140, "retention_keep_last": int(config.get("keep_last", 2))}
    provenance["input_normalize_waveform"] = bool(model.input_normalize_waveform)
    provenance["implementation"] = {"actual_training_source_sha256": implementation_sources(),
                                    "resume_receipt": implementation, "amp_retry_policy": AMP_RETRY_POLICY}
    provenance["device_info"] = device_telemetry(device)
    provenance["optimizer"] = {"name": "torch.optim.AdamW", "weight_decay": "decoupled", "lr": 5e-5,
        "betas": [.9, .98], "eps": 1e-6, "weight_decay_coefficient": .01,
        "historical_bitwise_equivalence": False,
        "distinction": "Fairseq custom/fused Adam may order epsilon and bias correction differently",
        "reference": "https://github.com/facebookresearch/fairseq/blob/v0.12.2/fairseq/optim/adam.py"}
    write_json(output / "run.json", provenance)
    print(json.dumps({"stage": "train_start", "step": state["global_step"], "total_updates": total_updates,
                      "microbatch": microbatch, "accumulation": accumulation, "precision": precision,
                      "device_info": provenance["device_info"]}), flush=True)
    last_log, started, updates_this_call = time.monotonic(), time.monotonic(), 0
    checkpoint_seconds_total = validation_seconds_total = 0.0
    checkpoint_events = 0
    last_checkpoint_seconds = 0.0
    steady_started = None
    steady_nontraining_baseline = 0.0
    last_validation = None
    def training_timing(now):
        nontraining = checkpoint_seconds_total + validation_seconds_total
        return {"training_seconds_before_final_checkpoint": max(0.0, now - started - nontraining),
                "steady_training_seconds": (max(0.0, now - steady_started - nontraining + steady_nontraining_baseline)
                                             if steady_started is not None else None),
                "steady_updates": max(0, updates_this_call - 2), "timing_warmup_updates_excluded": 2,
                "checkpoint_seconds_total": checkpoint_seconds_total, "checkpoint_events": checkpoint_events,
                "validation_seconds_total": validation_seconds_total,
                "timing_basis": "wall time includes data reads; checkpoint and validation time excluded"}
    def synchronize_for_timing():
        if str(device).startswith("cuda"):
            torch.cuda.synchronize(device)
    def run_validation():
        nonlocal validation_seconds_total
        before = time.monotonic()
        try:
            return validate(model, _loader(config, "validation", 0), device=device, precision=precision, seed=seed + 1)
        finally:
            validation_seconds_total += time.monotonic() - before
    def checkpoint(is_best=False):
        nonlocal history, checkpoint_seconds_total, checkpoint_events, last_checkpoint_seconds
        before = time.monotonic()
        payload = {**state, "model": model.state_dict(), "optimizer": optimizer.state_dict(),
                   "scaler": scaler.state_dict(), "rng": capture_rng(), "versions": versions}
        history, state["best_checkpoint"] = _save_checkpoint(output, payload, history, is_best=is_best,
                                                            keep_last=int(config.get("keep_last", 2)))
        if is_best:
            _atomic_torch_save(output / "best_encoder.pt", model.wav2vec2.state_dict())
            write_json(output / "best_encoder.json", {"sha256": digest(output / "best_encoder.pt"),
                       "step": state["global_step"], "validation": state["best_validation"],
                       "normalize_waveform": bool(model.input_normalize_waveform),
                       "initial_encoder": config["initial_encoder"], "run_signature": signature})
        last_checkpoint_seconds = time.monotonic() - before
        checkpoint_seconds_total += last_checkpoint_seconds
        checkpoint_events += 1
        return last_checkpoint_seconds
    model.train()
    for epoch in range(state["epoch"], epochs):
        state["epoch"] = epoch
        loader = iter(_loader(config, "train", epoch, state["consumed"]))
        while True:
            batches = []
            for _ in range(accumulation):
                batch = next(loader, None)
                if batch is None:
                    break
                batches.append(batch)
            if not batches:
                break
            masked_count, loss_sum, norm, retries = backward_group(
                model, optimizer, scaler, batches, device=device, precision=precision)
            lr = learning_rate(state["global_step"], total_updates, warmup_updates=int(config.get("warmup_updates", 5000)))
            for group in optimizer.param_groups:
                group["lr"] = lr
            scaler.step(optimizer); scaler.update()
            state["amp_overflow_retries"] = state.get("amp_overflow_retries", 0) + retries
            update = state["global_step"] + 1
            state["global_step"] = update; updates_this_call += 1
            for batch in batches:
                for tar_path, member_index in batch["cursor"]:
                    if state["consumed"].get(tar_path, 0) != member_index:
                        raise ValueError("non-contiguous committed audio cursor")
                    state["consumed"][tar_path] = member_index + 1
            now = time.monotonic()
            if now - last_log >= 60 or updates_this_call == 1:
                progress = {"stage": "train", "epoch": epoch + 1, "step": update, "total_updates": total_updates,
                            "loss": loss_sum / masked_count, "lr": lr, "grad_norm": float(norm),
                             "amp_overflow_retries": state["amp_overflow_retries"], "loss_scale": float(scaler.get_scale()),
                            "updates_per_hour": updates_this_call * 3600 / max(.001, now - started),
                            **training_timing(now),
                            "device_info": device_telemetry(device)}
                write_json(output / "progress.json", progress); print(json.dumps(progress), flush=True); last_log = now
            is_best = False
            if update % int(config.get("validation_interval_updates", 1000)) == 0:
                last_validation = run_validation()
                is_best = state["best_validation"] is None or last_validation["masked_objective"] < state["best_validation"]["masked_objective"]
                if is_best:
                    state["best_validation"] = {**last_validation, "step": update}
                write_json(output / "validation_latest.json", {**last_validation, "step": update})
            if is_best or update % int(config.get("checkpoint_interval_updates", 1000)) == 0:
                checkpoint(is_best)
            if updates_this_call == 2:
                synchronize_for_timing()
                steady_started = time.monotonic()
                steady_nontraining_baseline = checkpoint_seconds_total + validation_seconds_total
            if stop_after_updates is not None and updates_this_call >= stop_after_updates:
                synchronize_for_timing()
                timing = training_timing(time.monotonic())
                final_checkpoint_seconds = checkpoint()
                result = {"status": "pilot_stopped", "step": update, "total_updates": total_updates,
                          "elapsed_seconds": time.monotonic() - started, "updates_this_call": updates_this_call,
                          **timing, "final_checkpoint_seconds": final_checkpoint_seconds,
                          "checkpoint_seconds_total": checkpoint_seconds_total, "checkpoint_events": checkpoint_events,
                          "device_info": device_telemetry(device)}
                write_json(output / "summary.json", result); return result
        state["epoch"] = epoch + 1; state["consumed"] = {}
        last_validation = run_validation()
        is_best = state["best_validation"] is None or last_validation["masked_objective"] < state["best_validation"]["masked_objective"]
        if is_best:
            state["best_validation"] = {**last_validation, "step": state["global_step"]}
        checkpoint(is_best)
    result = {"status": "complete", "step": state["global_step"], "total_updates": total_updates,
              "epochs": epochs, "best_validation": state["best_validation"], "best_checkpoint": state["best_checkpoint"],
              "elapsed_seconds": time.monotonic() - started, "updates_this_call": updates_this_call,
              **training_timing(time.monotonic()), "final_checkpoint_seconds": last_checkpoint_seconds,
              "device_info": device_telemetry(device)}
    write_json(output / "summary.json", result)
    return result


def smoke(output_dir, *, device="cpu"):
    """Small official-model backward/optimizer/checkpoint smoke, no real audio."""
    import torch
    output = Path(output_dir); output.mkdir(parents=True, exist_ok=True)
    seed_everything(20261103)
    model = build_model(tiny=True).to(device).train()
    optimizer = make_optimizer(model.parameters())
    waveforms = torch.randn(2, 80000, device=device) * .01
    labels = torch.randint(200, (2, 249), device=device)
    masked, unmasked, penalty = model(waveforms, labels)
    loss, count = objective_sum(masked, penalty)
    (loss / count).backward()
    torch.nn.utils.clip_grad_norm_(model.parameters(), 10, error_if_nonfinite=True)
    optimizer.step()
    path = output / "synthetic-smoke.pt"
    _atomic_torch_save(path, {"model": model.state_dict(), "optimizer": optimizer.state_dict(), "rng": capture_rng()})
    restored = build_model(tiny=True).to(device)
    checkpoint = torch.load(path, map_location=device, weights_only=False)
    restored.load_state_dict(checkpoint["model"], strict=True)
    if not all(torch.equal(value, restored.state_dict()[key]) for key, value in model.state_dict().items()):
        raise ValueError("checkpoint round trip changed tensors")
    result = {"status": "synthetic_smoke_passed", "masked_frames": count, "classes_with_positive": masked.shape[1],
              "loss": float(loss.detach() / count), "unmasked_skipped": unmasked is None,
              "checkpoint_sha256": digest(path), "actual_corpus_training": False}
    write_json(output / "smoke.json", result); return result


def amp_smoke(output_dir, *, device="cuda"):
    """Tiny actual-CUDA GradScaler overflow/replay proof before a long resume."""
    import torch
    if torch.device(device).type != "cuda" or not torch.cuda.is_available():
        raise ValueError("AMP overflow smoke requires CUDA")
    seed_everything(20261103)

    class Probe(torch.nn.Module):
        def __init__(self):
            super().__init__(); self.linear = torch.nn.Linear(4, 2); self.draws = []
        def forward(self, waveform, labels):
            draw = torch.rand((), device=waveform.device); self.draws.append(float(draw))
            logits = self.linear(waveform + draw)
            return logits, None, self.linear.weight.float().square().mean() * .01

    model = Probe().to(device).train()
    injected = []
    def inject_once(gradient):
        if not injected:
            injected.append(True)
            return torch.full_like(gradient, float("inf"))
        return gradient
    handle = model.linear.weight.register_hook(inject_once)
    optimizer = make_optimizer(model.parameters())
    commits = []
    original_step = optimizer.step
    def step(*args, **kwargs):
        commits.append(True)
        return original_step(*args, **kwargs)
    optimizer.step = step
    scaler = torch.cuda.amp.GradScaler(enabled=True)
    before = float(scaler.get_scale())
    batch = {"waveform": torch.ones(2, 4, device=device),
             "labels": torch.zeros(2, 1, dtype=torch.long, device=device)}
    _, _, _, retries = backward_group(model, optimizer, scaler, [batch], device=device, precision="fp16")
    if (retries != 1 or commits or len(model.draws) != 2 or model.draws[0] != model.draws[1]
            or scaler.get_scale() != before / 2 or scaler.state_dict()["_growth_tracker"] != 0):
        raise ValueError("actual CUDA AMP skip/backoff/RNG replay proof failed")
    scaler.step(optimizer); scaler.update(); handle.remove()
    if len(commits) != 1 or not all(bool(torch.isfinite(p).all()) for p in model.parameters()):
        raise ValueError("actual CUDA AMP retry did not produce one finite optimizer commit")
    result = {"status": "amp_overflow_smoke_passed", "policy": AMP_RETRY_POLICY,
              "retries": retries, "optimizer_commits": len(commits), "same_rng_replayed": True,
              "scale_before": before, "scale_after": float(scaler.get_scale()),
              "implementation_sha256": digest(__file__), "device_info": device_telemetry(device)}
    write_json(Path(output_dir) / "amp_smoke.json", result)
    return result


