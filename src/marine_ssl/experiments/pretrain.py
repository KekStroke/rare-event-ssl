"""Single-GPU HuBERT/AVES DAPT with the historical masked cosine-NCE objective.

Targets are generated by ``codebook sample`` (GPU), ``fit`` (CPU), ``label``
(GPU), then consumed here. Pilot caps never shorten the recorded LR schedule.
"""
